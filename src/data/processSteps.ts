const PROCESS_CONTACT = 'Yeni Yazılım / Dijital Ürün Projesi';

function step(
  item: Omit<SolutionDetail, 'problems' | 'ctaLabel' | 'ctaMessage' | 'contactType'> &
    Partial<Pick<SolutionDetail, 'problems' | 'ctaLabel' | 'ctaMessage' | 'contactType'>>
): SolutionDetail {
  return {
    ...item,
    problems: item.problems ?? [],
    ctaLabel: item.ctaLabel ?? 'Projenizi Birlikte Planlayalım',
    contactType: item.contactType ?? PROCESS_CONTACT,
    ctaMessage:
      item.ctaMessage ??
      `${item.modalTitle ?? item.title} aşaması üzerinden yeni bir yazılım / dijital ürün projesini konuşmak istiyorum.`,
    category: item.category ?? 'Süreç',
    introLabel: item.introLabel ?? '',
    hoverActionLabel: item.hoverActionLabel ?? 'İşleyişi Gör →',
    visual: item.visual ?? 'process',
  };
}

