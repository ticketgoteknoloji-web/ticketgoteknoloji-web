const byId = new Map(featureCatalog.map((item) => [item.id, item]));

const aliases: Record<string, string> = {
  'why-security': 'security',
  'why-cloud': 'cloud',
  'why-ai': 'ai',
  'tech-ai': 'ai',
  'tech-cloud': 'cloud',
  'tech-security': 'security',
  'cap-crm': 'crm',
};

export function getFeature(id: string): SolutionDetail | undefined {
  return byId.get(aliases[id] ?? id);
}

export function featuresByIds(ids: readonly string[]): SolutionDetail[] {
  return ids
    .map((id) => getFeature(id))
    .filter((item): item is SolutionDetail => Boolean(item));
}

export function overlayFeature(id: string, patch: Partial<SolutionDetail>): SolutionDetail | undefined {
  const base = getFeature(id);
  if (!base) return undefined;
  return { ...base, ...patch };
}
